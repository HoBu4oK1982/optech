export function getDict(locale: string): Dict {
  return dictionaries[locale] || dictionaries.ru;
}

// Аналог t() из react-i18next: t('key') -> строка (фолбэк на сам ключ).
export function makeT(locale: string) {
  const d = getDict(locale);
  return (key: string): string => d[key] ?? key;
}

// Рендер строк вида "Оставить <1 />заявку" с переносом <br/> (как <Trans>).
export function renderWithBr(text: string): (string | null)[] {
  return text.split(/<\d+\s*\/>/g).flatMap((part, i) =>
    i === 0 ? [part] : [null, part]
  );
}
